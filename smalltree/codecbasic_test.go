package smalltree

import "testing"

func TestCodecBasic(t *testing.T) {
	cbm := NewCodecBasicMaker(ID16[HashIndexIdType]{})
	// Some bytes that vaguely mean node 0 is a slots node
	indexBytes := []byte{0x01, 0x00}
	nodesBytes := []byte{0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F,
		0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F}
	cb := cbm.MakeCodec(indexBytes, nodesBytes)
	n := cb.GetNode(0)
	if n.IsLeafNode() {
		t.Error("Not expecting a leaf node")
	}
	sn := n.GetSlotsNode()
	id := sn.GetSlotNode(15)
	if id != 0x0F0E {
		t.Error("Expected 0x0F0E, got", id)
	}
}
